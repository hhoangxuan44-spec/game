#!/usr/bin/env python3
"""server/data/*.json -> embedded/Data.cs (string tables; no primitive array literals so the merge stays simple)."""
import json
import os

root = os.path.dirname(os.path.abspath(__file__))
cards = json.load(open(os.path.join(root, "..", "server", "data", "cards.json"), encoding="utf-8"))
cust = json.load(open(os.path.join(root, "..", "server", "data", "customization.json"), encoding="utf-8"))

cl = ["%s|%s|%s|%s|%s" % (c["id"], c["prefab"], c["t"], c["kind"], ",".join(c["requires"] or [])) for c in cards]
ul = ["%s|%s|%s|%s|%d" % (c["name"], c["hero"], c["category"], c["currency"], c["price"]) for c in cust]

with open(os.path.join(root, "Data.cs"), "w", encoding="utf-8") as f:
    f.write("// GENERATED by embedded/gen_data.py from server/data/*.json -- do not edit.\n")
    f.write("namespace MonsuOffline\n{\n    public static class Data\n    {\n")
    f.write('        public const string Cards = "%s";\n' % ";".join(cl))
    f.write('        public const string Customization = "%s";\n' % ";".join(ul))
    f.write("    }\n}\n")
print("Data.cs written:", len(cl), "cards,", len(ul), "customization items")
